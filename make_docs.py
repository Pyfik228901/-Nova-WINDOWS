import os

# Создаем папку docs, если она еще не существует
os.makedirs("docs", exist_ok=True)

# Текст полной документации языка NovaScript
docs_content = """=============================================
ДОКУМЕНТАЦИЯ ЯЗЫКА NOVASCRIPT
=============================================

1. ПЕРЕМЕННЫЕ
   - `let имя = значение` — объявление и инициализация переменной.
     Пример: let score = 100

2. ВЫВОД ДАННЫХ
   - `print(выражение)` — выводит значение переменной, строки или числа в консоль.
     Пример: print("Привет, мир!")

3. УСЛОВНЫЕ ОПЕРАТОРЫ
   - `if условие { ... } else { ... }` — ветвление кода.
     Поддерживаемые операторы сравнения: ==, !=, <, >, <=, >=.
     Пример:
     if score >= 80 {
         print("Отлично!")
     } else {
         print("Можно лучше")
     }

4. ЦИКЛЫ
   - `while условие { ... }` — цикл с предусловием.
     Пример:
     let i = 0
     while i < 3 {
         print(i)
         i = i + 1
     }

5. ФУНКЦИИ
   - `func имя(параметры) { ... return значение ... }` — создание пользовательской функции.
     Пример:
     func multiply(a, b) {
         return a * b
     }

6. СПИСКИ (МАССИВЫ)
   - `[элемент1, элемент2, ...]` — создание списков для хранения коллекций или карт уровней 2D-игр.
     Пример: let inventory = ["Меч", "Зелье", "Щит"]

7. ВСТРОЕННЫЕ СИСТЕМНЫЕ ФУНКЦИИ
   - `input(промпт)` — выводит текст приглашения и считывает ввод пользователя.
     Пример: let name = input("Как вас зовут? ")
   - `random(min, max)` — генерирует случайное целое число в заданном диапазоне.
     Пример: let damage = random(10, 25)
   - `browse(url)` — открывает указанный URL или локальный файл (например, "index.html") в системном браузере.
     Пример: browse("index.html")

8. КОММЕНТАРИИ
   - `// Текст` — однострочный комментарий, который игнорируется интерпретатором.
"""

# Сохраняем в файл docs/main.txt
file_path = os.path.join("docs", "main.txt")
with open(file_path, "w", encoding="utf-8") as f:
    f.write(docs_content)

print("✅ Папка 'docs' и файл 'docs/main.txt' успешно созданы!")